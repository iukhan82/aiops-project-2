"""P09.07: the source of truth for how the platform's controls line up against security, privacy and AI frameworks.

    python source-code/security/framework_mapping.py            # rewrite framework_mapping.json
    python source-code/security/framework_mapping.py --check    # fail if the JSON on disk is not what this file produces

This file holds the mapping (which controls and documents stand behind which framework item, who owns it, what is missing);
`verify_control_mapping.py` checks it against the real control catalogue, evidence and register, and renders the tables in
`docs/security/CONTROL_MAPPING.md`.

WHAT THIS IS NOT. It is a mapping and a gap list for an academic prototype. It is not an assessment against any framework and
makes no claim of compliance, conformity or certification with any of them (ISO/IEC 27001, NIST CSF, ETSI EN 303 645, IEC 62443,
OWASP ASVS, NIST AI RMF, ISO/IEC 42001, GDPR). A framework item lists what the platform does that relates to it and what evidence
exists; the standard's own wording, scope and audit rules are not applied here. GDPR and the EU AI Act are legal questions for
qualified counsel; nothing here is legal advice.

Coverage is COMPUTED from the controls the item cites, never written down:

    evidenced     every cited control is `implemented` (its evidence passes today)
    partial       at least one cited control is implemented or partial, and something is missing
    documented    no control cited, but a document records the intent (intent, not enforcement)
    gap           applicable, and neither a working control nor a document exists (or only planned controls do)
    out_of_scope  not applicable to a software prototype with no operating organisation, staff or premises (reason given)
"""

