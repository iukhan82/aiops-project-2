def render(data: dict) -> str:
    return json.dumps(data, indent=2, sort_keys=False, ensure_ascii=False) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    wanted = render(build())
    if args.check:
        current = (
            OUTPUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUTPUT.is_file() else ""
        )
        if current != wanted:
            print(f"{OUTPUT} is out of date; run security/framework_mapping.py", file=sys.stderr)
            return 1
        print("framework mapping is current")
        return 0
    OUTPUT.write_text(wanted, encoding="utf-8", newline="\n")
    print(
        f"wrote {OUTPUT} ({sum(len(f['items']) for f in FRAMEWORKS)} items in {len(FRAMEWORKS)} frameworks)"
    )
    return 0


