"""P08.03: build and verify the design handoff.

    python source-code/frontend/tools/design.py --build   # tokens.css and the generated tables
    python source-code/frontend/tools/design.py           # verify everything, write evidence

Verification proves the handoff is real rather than described:
* `tokens.css` is exactly what `tokens.json` generates;
* every declared foreground/background pair meets its WCAG 2.2 minimum
  (4.5:1 text, 3:1 non-text), computed here, not asserted;
* every departure from the design system's MASTER.md is justified by a
  measurement that is re-run (the replaced value really does fail);
* every state a backend record can be in - read from the repositories and
  migrations, not retyped - has a label, a shape and a tone, and no two states
  of one domain share a shape or a label, so lifecycles are distinct in
  greyscale;
* every component section has purpose, anatomy, states, keyboard, ARIA, tokens
  and used-by; every token and screen it names exists; the screen composition
  table and the components' used-by lists agree in both directions.
"""

